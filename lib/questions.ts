/** 日付から決定的に選ぶ。全ユーザーが同じ日に同じ問いを受け取る。 */
export function questionForDate(date: string): DailyQuestion {
  const days = Math.floor(Date.parse(`${date}T00:00:00Z`) / 86400000);
  const q = DAILY_QUESTIONS[((days % DAILY_QUESTIONS.length) + DAILY_QUESTIONS.length) % DAILY_QUESTIONS.length];
  return { date, id: q.id, text: q.text };
}

export function today(): string {
  return new Date().toISOString().slice(0, 10);
}
