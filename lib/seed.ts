/** 指定の問いが最後に出た日付（今日を含む、直近60日から探す）。 */
function lastDateFor(questionId: string): string | null {
  const now = Date.now();
  for (let i = 0; i < 60; i++) {
    const date = new Date(now - i * 86400000).toISOString().slice(0, 10);
    if (questionForDate(date).id === questionId) return date;
  }
  return null;
}

export function seedDatabase(): Database {
  const db = emptyDatabase();

  db.users = SEED_USERS.map((u, i) => ({
    ...u,
    id: `usr_${String(i + 1).padStart(2, "0")}`,
    createdAt: new Date(Date.now() - (SEED_USERS.length - i) * 86400000).toISOString(),
  }));

  let n = 0;
  for (const q of DAILY_QUESTIONS) {
    const rows = ANSWERS[q.id];
    if (!rows) continue;
    const date = lastDateFor(q.id);
    if (!date) continue;
    for (const [userIndex, body] of rows) {
      const user = db.users[userIndex];
      if (!user) continue;
      db.answers.push({
        id: `ans_${String(++n).padStart(3, "0")}`,
        userId: user.id,
        questionId: q.id,
        body,
        // その日の夜に答えた体にする
        createdAt: `${date}T13:${String(10 + (n % 45)).padStart(2, "0")}:00.000Z`,
      });
    }
  }

  return db;
}

